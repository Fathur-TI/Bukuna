export const ALL_QUIZZES = [...STORY_QUIZZES, ...GENERAL_QUIZZES];

export function getQuizByStoryId(storyId) {
  if (!storyId) return STORY_QUIZZES[0];
  const found = ALL_QUIZZES.find((q) => q.storyId === storyId || q.id === storyId);
  return found || null;
}
